def pb(pork, beef, chicken=None):
    """豬肉 / 牛肉 / (雞腿肉專區) 價格"""
    d = {"豬肉": pork, "牛肉": beef}
    if chicken is not None:
        d["雞腿肉"] = chicken
    return d


